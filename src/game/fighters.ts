export function getDisplayFighterMeta(
  fighterId: FighterId,
  authorizationMode: boolean,
): {
  name: string;
  showPortraitPhoto: boolean;
  isSubstitute: boolean;
} {
  const def = FIGHTERS[fighterId];
  if (def.requiresAuthorization && !authorizationMode) {
    return {
      name: def.fallbackAlias || def.title.toUpperCase(),
      showPortraitPhoto: false,
      isSubstitute: true,
    };
  }
  return {
    name: def.name,
    showPortraitPhoto: Boolean(def.portraitUrl),
    isSubstitute: false,
  };
}

export function getMasteryLevel(xp: number): { level: number; titleIdx: number; nextXp: number; pct: number } {
  const thresholds = [0, 150, 450, 900];
  let idx = 0;
  for (let i = thresholds.length - 1; i >= 0; i--) {
    if (xp >= thresholds[i]) {
      idx = i;
      break;
    }
  }
  const currentMin = thresholds[idx];
  const nextThreshold = thresholds[Math.min(thresholds.length - 1, idx + 1)] || 1500;
  const span = Math.max(150, nextThreshold - currentMin);
  const pct = idx === 3 ? 100 : Math.min(100, Math.round(((xp - currentMin) / span) * 100));
  return { level: idx + 1, titleIdx: idx, nextXp: nextThreshold, pct };
}

